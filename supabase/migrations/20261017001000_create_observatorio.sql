-- Contratos separados de public.* (Hacienda, Docsys, Aula), sin cambios a terceros.
CREATE SCHEMA IF NOT EXISTS observatorio;

CREATE TABLE IF NOT EXISTS observatorio.fuentes (
 id text PRIMARY KEY,
 nombre text NOT NULL,
 organismo text,
 url text,
 tipo text NOT NULL DEFAULT 'documento',
 clasificacion text NOT NULL DEFAULT 'publica_agregada'
  CHECK (clasificacion IN ('publica_agregada','interna','confidencial')),
 anio_publicacion integer,
 fecha_revision timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS observatorio.indicadores (
 id text PRIMARY KEY,
 nombre text NOT NULL,
 tema text NOT NULL,
 subtema text,
 definicion text,
 unidad text,
 formula text,
 dependencia_propuesta text,
 territorio char(5) NOT NULL DEFAULT '76670' CHECK (territorio='76670'),
 grupo text NOT NULL CHECK (grupo IN ('ICET','PDT','TERRIDATA','SECTORIAL','POLICIA')),
 estado text NOT NULL DEFAULT 'catalogado'
  CHECK (estado IN ('catalogado','revisado','validado','descartado')),
 visible boolean NOT NULL DEFAULT false,
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS observatorio.observaciones (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 indicador_id text NOT NULL REFERENCES observatorio.indicadores(id),
 fuente_id text REFERENCES observatorio.fuentes(id),
 id_en_fuente text,
 territorio char(5) NOT NULL DEFAULT '76670' CHECK (territorio='76670'),
 alcance text NOT NULL DEFAULT 'municipal',
 anio integer,
 periodo_desde date,
 periodo_hasta date,
 fecha_corte date,
 valor numeric,
 numerador numeric,
 denominador numeric,
 unidad text NOT NULL,
 pagina int,
 nota text,
 estado text NOT NULL DEFAULT 'borrador'
  CHECK (estado IN ('borrador','por_revisar','revisado','validado','rechazado')),
 aprobado_por uuid,
 aprobado_en timestamptz,
 ingresado_en timestamptz NOT NULL DEFAULT now(),
 CHECK (denominador IS NULL OR denominador<>0),
 CHECK (estado<>'validado' OR (aprobado_por IS NOT NULL AND aprobado_en IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_obs_fuente_registro
 ON observatorio.observaciones (indicador_id, fuente_id, id_en_fuente)
 WHERE id_en_fuente IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_obs_indicator_year
 ON observatorio.observaciones (indicador_id, anio DESC, estado);
CREATE TABLE IF NOT EXISTS observatorio.miembros (
 user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 rol text NOT NULL CHECK (rol IN ('lector_interno','digitador','validador','admin')),
 activo boolean NOT NULL DEFAULT true,
 creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS observatorio.importaciones (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 nombre_archivo text NOT NULL,
 sha256 text,
 estado text NOT NULL DEFAULT 'pendiente',
 responsable uuid REFERENCES auth.users(id),
 incidencias jsonb NOT NULL DEFAULT '[]'::jsonb,
 creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS observatorio.auditoria (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tabla text NOT NULL,
 registro_id text NOT NULL,
 accion text NOT NULL,
 usuario uuid,
 resumen jsonb NOT NULL DEFAULT '{}'::jsonb,
 creado_en timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE observatorio.fuentes ENABLE ROW LEVEL SECURITY;
ALTER TABLE observatorio.indicadores ENABLE ROW LEVEL SECURITY;
ALTER TABLE observatorio.observaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE observatorio.miembros ENABLE ROW LEVEL SECURITY;
ALTER TABLE observatorio.importaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE observatorio.auditoria ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA observatorio FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA observatorio TO anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA observatorio FROM PUBLIC, anon, authenticated;
GRANT SELECT ON observatorio.indicadores, observatorio.observaciones TO anon, authenticated;
DROP POLICY IF EXISTS catalogo_publico_revisado ON observatorio.indicadores;
CREATE POLICY catalogo_publico_revisado ON observatorio.indicadores
 FOR SELECT TO anon, authenticated
 USING (visible=true AND estado='validado');
DROP POLICY IF EXISTS observaciones_publicas_validadas ON observatorio.observaciones;
CREATE POLICY observaciones_publicas_validadas ON observatorio.observaciones
 FOR SELECT TO anon, authenticated
 USING (
  estado='validado' AND EXISTS (
   SELECT 1 FROM observatorio.indicadores i
   WHERE i.id=indicador_id AND i.visible AND i.estado='validado'
  )
 );
COMMENT ON SCHEMA observatorio IS
 'Datos abiertos San Pedro 76670; separado de Hacienda, Docsys y Aula; borradores restringidos.';
